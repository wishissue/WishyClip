// Generates app/src/main/java/org/wishyclip/app/ui/design/themes/Indigo.kt: the default palette family.
//
//   cd <scratch dir> && npm i @material/material-color-utilities
//   node tools/gen-themes.mjs <scratch>/node_modules/@material/material-color-utilities/index.js
//
// Method (a design relationship studied from Orion Store 2.x, re-derived here rather than copied):
// an indigo primary seed (#6366F1) with a lime tertiary accent (#A3E635), TONAL_SPOT scheme, spec 2025,
// primary chroma 64, tertiary chroma 56, quiet neutrals (chroma <= 5 / 10). Four surface families:
// Light, Dark, Dusk (a softer, bluer dark) and OLED (true black). The palette is generated from
// material-color-utilities (Apache-2.0); no Orion source file is used.
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
const { Hct, DynamicScheme, Variant, TonalPalette, argbFromHex, hexFromArgb } = await import(pathToFileURL(process.argv[2]).href);

const SEED = '#6366F1', TERT = '#A3E635', PC = 64, TC = 56;
const src = Hct.fromInt(argbFromHex(SEED)), t3 = Hct.fromInt(argbFromHex(TERT));
const mk = dark => new DynamicScheme({
  sourceColorHct: src, variant: Variant.TONAL_SPOT, contrastLevel: 0, isDark: dark, specVersion: '2025', platform: 'phone',
  primaryPalette: TonalPalette.fromHueAndChroma(src.hue, PC),
  secondaryPalette: TonalPalette.fromHueAndChroma(src.hue, Math.min(20, PC)),
  neutralPalette: TonalPalette.fromHueAndChroma(src.hue, Math.min(5, PC)),
  neutralVariantPalette: TonalPalette.fromHueAndChroma(src.hue, Math.min(10, PC)),
  tertiaryPalette: TonalPalette.fromHueAndChroma(t3.hue, TC),
});
const c = v => `Color(0xFF${hexFromArgb(v).slice(1).toUpperCase()})`;
const hex = h => `Color(0xFF${h.slice(1).toUpperCase()})`;

const light = mk(false), dark = mk(true);
const dusk = TonalPalette.fromHueAndChroma(src.hue, 14), duskV = TonalPalette.fromHueAndChroma(src.hue, 18);
const neutral = TonalPalette.fromHueAndChroma(src.hue, 5);
const d = n => c(dusk.tone(n)), o = n => c(neutral.tone(n));

const base = (s) => `    primary = ${c(s.primary)},
    onPrimary = ${c(s.onPrimary)},
    primaryContainer = ${c(s.primaryContainer)},
    onPrimaryContainer = ${c(s.onPrimaryContainer)},
    secondary = ${c(s.secondary)},
    onSecondary = ${c(s.onSecondary)},
    secondaryContainer = ${c(s.secondaryContainer)},
    onSecondaryContainer = ${c(s.onSecondaryContainer)},
    tertiary = ${c(s.tertiary)},
    onTertiary = ${c(s.onTertiary)},
    tertiaryContainer = ${c(s.tertiaryContainer)},
    onTertiaryContainer = ${c(s.onTertiaryContainer)},
    onSurface = ${c(s.onSurface)},
    outline = ${c(s.outline)},
    inverseSurface = ${c(s.inverseSurface)},
    inverseOnSurface = ${c(s.inverseOnSurface)},
    inversePrimary = ${c(s.inversePrimary)},
    errorContainer = ${c(s.errorContainer)},
    onErrorContainer = ${c(s.onErrorContainer)},
    danger = ${c(s.error)},`;

function family(name, isDark, s, surf) {
  // surf: surface, variant, onVariant, outlineVariant, lowest, low, container, high, highest, backdrop
  return `val ${name}Tokens = WishyTokens(
    name = "${{ IndigoLight: 'Indigo', IndigoDark: 'Indigo Dark', IndigoDusk: 'Indigo Dusk', IndigoOled: 'Indigo OLED' }[name]}",
    isDark = ${isDark},
${base(s)}
    surface = ${surf.surface},
    surfaceVariant = ${surf.variant},
    onSurfaceVariant = ${surf.onVariant},
    outlineVariant = ${surf.outlineVariant},
    surfaceContainerLowest = ${surf.lowest},
    surfaceContainerLow = ${surf.low},
    surfaceContainer = ${surf.container},
    surfaceContainerHigh = ${surf.high},
    surfaceContainerHighest = ${surf.highest},
    canvasBackdrop = ${surf.backdrop},
    toolRail = ${surf.container},
    timeline = ${surf.low},
    accent = ${c(s.tertiary)},
    onionPreviousTint = ${isDark ? '0xFFFF8A8F' : '0xFFE5484D'}.let { Color(it) },
    onionNextTint = ${isDark ? '0xFF72D6A0' : '0xFF237A4B'}.let { Color(it) },
    paper = Color(0xFFFFFFFF)
)`.replace(/Color\(0x[0-9A-F]{8}\)/g, m => m).replace(/(0xFF[0-9A-F]{6})\.let \{ Color\(it\) \}/g, 'Color($1)');
}

const out = `// Generated by tools/gen-themes.mjs (material-color-utilities, spec 2025, tonal spot). Do not edit by hand.
package org.wishyclip.app.ui.design.themes

import androidx.compose.ui.graphics.Color
import org.wishyclip.app.ui.design.WishyTokens

/**
 * The default palette family: indigo primary, lime tertiary, quiet blue-grey neutrals.
 * The drawing paper stays white in every variant; the canvas backdrop is the stage around it and
 * is always darker (dark themes) or tinted (light) so the sheet reads against it.
 */

${family('IndigoLight', false, light, {
  surface: c(light.surface), variant: c(light.surfaceVariant), onVariant: c(light.onSurfaceVariant), outlineVariant: c(light.outlineVariant),
  lowest: c(light.surfaceContainerLowest), low: c(light.surfaceContainerLow), container: c(light.surfaceContainer),
  high: c(light.surfaceContainerHigh), highest: c(light.surfaceContainerHighest), backdrop: c(light.surfaceContainerHigh) })}

${family('IndigoDark', true, dark, {
  surface: c(dark.surface), variant: c(dark.surfaceVariant), onVariant: c(dark.onSurfaceVariant), outlineVariant: c(dark.outlineVariant),
  lowest: c(dark.surfaceContainerLowest), low: c(dark.surfaceContainerLow), container: c(dark.surfaceContainer),
  high: c(dark.surfaceContainerHigh), highest: c(dark.surfaceContainerHighest), backdrop: c(dark.surfaceContainerLowest) })}

${family('IndigoDusk', true, dark, {
  surface: d(12), variant: d(26), onVariant: c(duskV.tone(76)), outlineVariant: c(duskV.tone(34)),
  lowest: d(8), low: d(15), container: d(18), high: d(22), highest: d(26), backdrop: d(8) })}

${family('IndigoOled', true, dark, {
  surface: 'Color(0xFF000000)', variant: o(14), onVariant: c(dark.onSurfaceVariant), outlineVariant: c(dark.outlineVariant),
  lowest: 'Color(0xFF000000)', low: o(4), container: o(7), high: o(10), highest: o(14), backdrop: 'Color(0xFF000000)' })}
`;
writeFileSync('app/src/main/java/org/wishyclip/app/ui/design/themes/Indigo.kt', out);
console.log('wrote Indigo.kt');
