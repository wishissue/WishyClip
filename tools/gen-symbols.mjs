function pathOf(name, fill) {
  const svg = readFileSync(join(src, 'rounded', fill ? `${name}-fill.svg` : `${name}.svg`), 'utf8');
  const ds = [...svg.matchAll(/ d="([^"]+)"/g)].map(m => m[1]);
  if (!ds.length) throw new Error(`no path in ${name}`);
  return ds;
}
// Symbols are drawn in a 960 box whose origin is at y = -960; the group moves it into view.
const xml = (name, ds) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded "${name}" (Apache-2.0). Generated by tools/gen-symbols.mjs; do not edit by hand. Tinted at the call site. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960">
  <group android:translateY="960">
${ds.map(d => `    <path android:fillColor="#FFFFFFFF" android:pathData="${d}"/>`).join('\n')}
  </group>
</vector>
`;

const pairs = [];
for (const [id, sym] of Object.entries(ICONS)) {
  writeFileSync(join(outDir, `ic_${id}.xml`), xml(sym, pathOf(sym, false)));
  let hasFill = true;
  try { writeFileSync(join(outDir, `ic_${id}_filled.xml`), xml(`${sym} (filled)`, pathOf(sym, true))); } catch { hasFill = false; }
  if (hasFill) pairs.push(id);
}

const kt = `// Generated by tools/gen-symbols.mjs. Do not edit by hand.
package org.wishyclip.app.ui.design

import org.wishyclip.app.R

/** Maps each outlined icon to its filled Material Symbols variant, used for selected / active states. */
internal object SelectedIcons {
    private val filled: Map<Int, Int> = mapOf(
${pairs.map(id => `        R.drawable.ic_${id} to R.drawable.ic_${id}_filled`).join(',\n')}
    )

    fun of(res: Int): Int = filled[res] ?: res
}
`;
writeFileSync('app/src/main/java/org/wishyclip/app/ui/design/SelectedIcons.kt', kt);

const kotlinNames = Object.keys(ICONS).map(id => id);
console.log(`wrote ${kotlinNames.length} icons, ${pairs.length} with filled variants`);
const nofill = kotlinNames.filter(i => !pairs.includes(i));
if (nofill.length) console.log('no filled variant (outlined reused):', nofill.join(', '));
