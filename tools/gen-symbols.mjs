//
//   cd <scratch dir> && npm i @material-symbols/svg-400
//   node tools/gen-symbols.mjs <scratch>/node_modules/@material-symbols/svg-400 app/src/main/res/drawable
//
// Source: https://github.com/marella/material-symbols (npm: @material-symbols/svg-400),
// which redistributes Google's Material Symbols (https://fonts.google.com/icons), Apache License 2.0.
//
// For every entry below this writes  ic_<id>.xml  (outlined, used for normal state) and
// ic_<id>_filled.xml (FILL 1, used for selected / active state), plus
// app/src/main/java/org/wishyclip/app/ui/design/SelectedIcons.kt, the lookup from one to the other.
// Icons are local vector drawables: nothing is loaded at runtime and no network is needed.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [src, outDir] = process.argv.slice(2);
if (!src || !outDir) { console.error('usage: node gen-symbols.mjs <svg-400 dir> <drawable dir>'); process.exit(1); }

